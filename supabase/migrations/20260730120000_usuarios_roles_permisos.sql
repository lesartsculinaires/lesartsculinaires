-- Usuarios, roles y permisos.
--
-- Modelo: un usuario tiene un rol; un rol tiene permisos por módulo, con las
-- cuatro acciones de la pantalla (ver / crear / editar / eliminar).
--
-- `modulos` es un catálogo con jerarquía de un nivel: una fila con `padre`
-- apuntando a otra es un sub-permiso, que en la interfaz aparece indentado
-- como "Módulo — Detalle (sub-permiso)".

create table if not exists public.roles (
  id          bigint generated by default as identity primary key,
  nombre      text unique not null,
  descripcion text,
  activo      boolean not null default true,
  -- Un rol administrador siempre puede todo y no se puede borrar. Sirve de
  -- salvavidas: sin esto, quitarse permisos a uno mismo deja el CRM sin nadie
  -- que pueda volver a entrar a esta pantalla.
  es_admin    boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.modulos (
  clave  text primary key,
  nombre text not null,
  -- Null en un módulo de primer nivel; la clave del padre en un sub-permiso.
  padre  text references public.modulos(clave) on delete cascade,
  orden  smallint not null default 0
);

create table if not exists public.rol_permisos (
  rol_id   bigint not null references public.roles(id)   on delete cascade,
  modulo   text   not null references public.modulos(clave) on delete cascade,
  ver      boolean not null default false,
  crear    boolean not null default false,
  editar   boolean not null default false,
  eliminar boolean not null default false,
  primary key (rol_id, modulo)
);

-- Un usuario de la aplicación, colgado de la cuenta de Supabase Auth.
create table if not exists public.usuarios (
  id         uuid primary key references auth.users(id) on delete cascade,
  nombre     text,
  correo     text not null,
  rol_id     bigint references public.roles(id) on delete set null,
  activo     boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_usuarios_rol on public.usuarios (rol_id);

drop trigger if exists trg_roles_updated on public.roles;
create trigger trg_roles_updated before update on public.roles
  for each row execute function public.set_updated_at();

drop trigger if exists trg_usuarios_updated on public.usuarios;
create trigger trg_usuarios_updated before update on public.usuarios
  for each row execute function public.set_updated_at();

