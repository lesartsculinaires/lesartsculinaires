-- El administrador arranca con todo encendido.
insert into public.rol_permisos (rol_id, modulo, ver, crear, editar, eliminar)
select r.id, m.clave, true, true, true, true
from public.roles r cross join public.modulos m
where r.es_admin
on conflict (rol_id, modulo) do nothing;

-- Ventas: todo menos administrar usuarios y sin borrar nada.
insert into public.rol_permisos (rol_id, modulo, ver, crear, editar, eliminar)
select r.id, m.clave, m.clave <> 'usuarios', m.clave <> 'usuarios', m.clave <> 'usuarios', false
from public.roles r cross join public.modulos m
where r.nombre = 'Ventas'
on conflict (rol_id, modulo) do nothing;

-- Toda cuenta que ya exista en Auth entra como administrador: si no, nadie
-- podría abrir esta pantalla para repartir los permisos.
insert into public.usuarios (id, nombre, correo, rol_id)
select u.id,
       coalesce(u.raw_user_meta_data->>'full_name', split_part(u.email, '@', 1)),
       u.email,
       (select id from public.roles where es_admin limit 1)
from auth.users u
on conflict (id) do nothing;

-- ---------------------------------------------------------------- RLS
--
-- `es_admin()` es SECURITY DEFINER a propósito: las políticas de `usuarios`
-- necesitan leer `usuarios` para decidir, y una política que se consulta a sí
-- misma entra en recursión infinita. Al correr como su creador, la función
-- salta el RLS y corta el ciclo.
create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((
    select r.es_admin
    from public.usuarios u
    join public.roles r on r.id = u.rol_id
    where u.id = (select auth.uid()) and u.activo
  ), false);
$$;

revoke execute on function public.es_admin() from anon;

alter table public.roles        enable row level security;
alter table public.modulos      enable row level security;
alter table public.rol_permisos enable row level security;
alter table public.usuarios     enable row level security;

-- Todos los que iniciaron sesión leen el catálogo: la interfaz necesita saber
-- qué puede hacer el usuario antes de dibujar el menú.
drop policy if exists lee_roles on public.roles;
create policy lee_roles on public.roles
  for select to authenticated using (true);

drop policy if exists lee_modulos on public.modulos;
create policy lee_modulos on public.modulos
  for select to authenticated using (true);

drop policy if exists lee_permisos on public.rol_permisos;
create policy lee_permisos on public.rol_permisos
  for select to authenticated using (true);

-- Cada quien ve su propia ficha; el administrador ve y edita todas.
drop policy if exists lee_usuarios on public.usuarios;
create policy lee_usuarios on public.usuarios
  for select to authenticated
  using (id = (select auth.uid()) or public.es_admin());

-- Sólo el administrador reparte roles y permisos.
drop policy if exists admin_roles on public.roles;
create policy admin_roles on public.roles
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

drop policy if exists admin_permisos on public.rol_permisos;
create policy admin_permisos on public.rol_permisos
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

drop policy if exists admin_usuarios on public.usuarios;
create policy admin_usuarios on public.usuarios
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- Impedir que se borre o se degrade el último rol administrador.
create or replace function public.protege_admin()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.es_admin then
      raise exception 'No se puede eliminar el rol administrador.';
    end if;
    return old;
  end if;

  if old.es_admin and not new.es_admin
     and not exists (select 1 from public.roles
                     where es_admin and id <> old.id) then
    raise exception 'Debe quedar al menos un rol administrador.';
  end if;
  return new;
end $$;

drop trigger if exists trg_protege_admin on public.roles;
create trigger trg_protege_admin before update or delete on public.roles
  for each row execute function public.protege_admin();
