-- Política inicial: cualquier usuario autenticado puede leer y escribir.
-- Endurecer después (ej. que cada vendedor vea solo sus oportunidades).
do $$
declare t text;
begin
  foreach t in array array['vendedores','territorios','canales','productos','etapas','estados',
                           'clientes','oportunidades','oportunidad_notas']
  loop
    execute format('drop policy if exists %I on public.%I', 'auth_all_'||t, t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (true) with check (true)',
      'auth_all_'||t, t);
  end loop;
end $$;
