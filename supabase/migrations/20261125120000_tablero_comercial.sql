-- El Tablero Comercial de los institutos (pedido del 9/11/2026).
--
-- La Dirección armó una plantilla en Excel —«Tablero Comercial Institutos»—
-- que llenan cada lunes el Director de Marketing y la Gerente de Ventas, y
-- que la Dirección revisa. Este archivo trae esa plantilla al CRM: lo que el
-- CRM ya sabe (leads, contactados, inscritos, venta) sale solo, y lo demás
-- (pauta, alcance, metas, plan de acciones…) lo llena cada área acá.
--
-- Cada CRM guarda lo suyo: el de LAC lo de LAC y el de HC lo de HC. Por eso
-- ninguna tabla tiene columna «empresa»: la empresa es la base en la que está.
-- El sitio que junta las dos para la Dirección lee de las dos bases.
--
-- ============================================================================
-- POR QUÉ CAMPO Y VALOR, Y NO UNA COLUMNA POR DATO
-- ============================================================================
--
-- La plantilla tiene más de cincuenta datos semanales y la Dirección la va a
-- seguir ajustando: un canal nuevo, una meta nueva. Con una columna por dato,
-- cada ajuste es una migración. Con «campo y valor», es una línea en el
-- catálogo de la aplicación (`lib/tablero/campos.ts`), que además dice quién
-- llena cada campo y cómo se muestra.
--
-- Lo que sí tiene forma propia son las listas que se llenan fila por fila:
-- los grupos en venta, el plan de acciones y la actividad de cada vendedora.
--
-- ============================================================================
-- QUIÉN VE Y QUIÉN LLENA
-- ============================================================================
--
-- Cinco casillas en Usuarios y Roles:
--
--   tablero              ver el Tablero Comercial
--   tablero.mk           llenar lo de Marketing
--   tablero.ventas       llenar lo de Ventas
--   tablero.actividad    llenar la actividad propia de la semana
--   tablero.metas        definir metas, cupos y precios (Dirección)
--
-- En este CRM un módulo sin permiso guardado lo ve todo el mundo. El Tablero
-- trae metas y montos de venta, así que acá se guarda «no» para cada rol que
-- no es de dirección: queda visible sólo para Dirección hasta que se decidan
-- los roles, y se abre desde Usuarios y Roles.

begin;

-- ------------------------------------------------------- los datos de cada semana

-- Una fila por semana y por dato. La semana es la del lunes, como en la
-- plantilla; a qué mes suma lo decide la aplicación (el mes del jueves).
--
-- `valor` vacío no es lo mismo que cero: vacío es «todavía no se cargó», y el
-- Tablero lo usa para prorratear las metas por las semanas que van cargadas.
create table if not exists public.tablero_semanal (
  semana          date        not null check (extract(isodow from semana) = 1),
  campo           text        not null check (campo ~ '^(mk|ventas)\.[a-z0-9_]+$'),
  valor           numeric,
  actualizado_por uuid        references auth.users(id) on delete set null,
  actualizado_en  timestamptz not null default now(),
  primary key (semana, campo)
);

comment on table public.tablero_semanal is
  'Lo que llenan Marketing (mk.*) y Ventas (ventas.*) cada semana. Un campo de la plantilla por fila.';

-- ------------------------------------------------------------------ las metas

-- Las que cambian cada mes (venta nueva, leads, presupuesto de pauta) y las
-- fijas (cursos cortos al mes, contactados en 24 h…), en la misma tabla: las
-- fijas van con `mes` vacío. La clave primaria no admite vacíos, por eso hay
-- un índice único aparte para cada caso.
create table if not exists public.tablero_metas (
  id              bigint generated by default as identity primary key,
  mes             date        check (mes is null or extract(day from mes) = 1),
  clave           text        not null check (clave ~ '^[a-z0-9_]+$'),
  valor           numeric,
  actualizado_por uuid        references auth.users(id) on delete set null,
  actualizado_en  timestamptz not null default now()
);

create unique index if not exists tablero_metas_del_mes
  on public.tablero_metas (mes, clave) where mes is not null;
create unique index if not exists tablero_metas_fijas
  on public.tablero_metas (clave) where mes is null;

comment on table public.tablero_metas is
  'Metas del Tablero Comercial. Con mes: la meta de ese mes. Sin mes: meta fija que vale todos los meses.';

-- --------------------------------------------------------- los grupos en venta

-- Lo define la Dirección (programa, fechas, precios, cupo) y Ventas actualiza
-- cada lunes las reservas e inscritos. Cuando cada lead quede ligado a su
-- grupo en la ficha, esas dos cifras van a salir solas del CRM.
create table if not exists public.tablero_grupos (
  id                   bigint generated by default as identity primary key,
  producto_id          bigint      references public.productos(id) on delete set null,
  programa             text        not null,
  grupo                text        not null,
  dias                 text,
  horario              text,
  duracion_meses       numeric,
  inicio               date,
  matricula_1          numeric,
  matricula_2          numeric,
  mensualidad          numeric,
  graduacion           numeric,
  mensualidad_preventa numeric,
  cupo                 integer,
  reservas             integer,
  inscritos            integer,
  activo               boolean     not null default true,
  actualizado_por      uuid        references auth.users(id) on delete set null,
  actualizado_en       timestamptz not null default now()
);

comment on table public.tablero_grupos is
  'Grupos en venta: cupos, precios, reservas (precio de preventa) e inscritos (precio regular).';

-- ---------------------------------------------------------- el plan de acciones

create table if not exists public.tablero_acciones (
  id               bigint generated by default as identity primary key,
  tipo             text        not null,
  accion           text        not null,
  responsable      text        not null check (responsable in ('MK', 'Ventas')),
  persona          text,
  fecha            date,
  estado           text        not null default 'Planificada'
                               check (estado in ('Planificada', 'Hecha', 'Reprogramada', 'Cancelada')),
  costo            numeric,
  leads_esperados  integer,
  leads_obtenidos  integer,
  inscritos        integer,
  venta            numeric,
  creado_por       uuid        references auth.users(id) on delete set null,
  creado_en        timestamptz not null default now(),
  actualizado_por  uuid        references auth.users(id) on delete set null,
  actualizado_en   timestamptz not null default now()
);

comment on table public.tablero_acciones is
  'Cada acción de MK o Ventas: se anota antes (qué, cuándo, costo, leads esperados) y se completa después con lo que dio.';

-- ------------------------------------------------- la actividad de cada persona

-- Una fila por semana y por vendedora. Lo que el CRM ya registra (mensajes,
-- llamadas por WhatsApp, citas del Calendario, ventas ganadas) se muestra al
-- lado y no hace falta escribirlo; acá va lo que pasa fuera del CRM.
create table if not exists public.tablero_actividad (
  semana          date        not null check (extract(isodow from semana) = 1),
  vendedor_id     bigint      not null references public.vendedores(id) on delete cascade,
  campo           text        not null check (campo ~ '^[a-z0-9_]+$'),
  valor           numeric,
  actualizado_por uuid        references auth.users(id) on delete set null,
  actualizado_en  timestamptz not null default now(),
  primary key (semana, vendedor_id, campo)
);

comment on table public.tablero_actividad is
  'Actividad semanal por vendedora: llamadas, salidas de campo, eventos… lo que el CRM no ve solo.';

-- --------------------------------------------- lo que vendió cada persona en el mes

create table if not exists public.tablero_ventas_persona (
  mes             date        not null check (extract(day from mes) = 1),
  vendedor_id     bigint      not null references public.vendedores(id) on delete cascade,
  campo           text        not null check (campo ~ '^[a-z0-9_]+$'),
  valor           numeric,
  actualizado_por uuid        references auth.users(id) on delete set null,
  actualizado_en  timestamptz not null default now(),
  primary key (mes, vendedor_id, campo)
);

comment on table public.tablero_ventas_persona is
  'Cierre del mes por persona: cantidades y montos vendidos. Sin comisiones: Dirección las calcula aparte.';

-- ------------------------------------------------ lo que cada área tiene que decir

-- Un texto por hoja y por mes: lo que el área quiere explicar de sus números
-- (por qué bajaron los leads, qué se hará distinto). Lo pidió la escuela al
-- traer la plantilla.
create table if not exists public.tablero_comentarios (
  mes             date        not null check (extract(day from mes) = 1),
  hoja            text        not null check (hoja ~ '^[a-z_]+$'),
  texto           text        not null default '',
  actualizado_por uuid        references auth.users(id) on delete set null,
  actualizado_en  timestamptz not null default now(),
  primary key (mes, hoja)
);

comment on table public.tablero_comentarios is
  'Comentario de cada área sobre su hoja del Tablero, mes por mes.';

-- -------------------------------------------------------------------- permisos

-- Quién puede escribir cada hoja. Ver: quien tenga «tablero».
create or replace function public.puede_llenar_tablero(p_hoja text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when p_hoja in ('mk')                         then public.puede('tablero.mk', 'editar')
    when p_hoja in ('ventas', 'ventas_persona')   then public.puede('tablero.ventas', 'editar')
    when p_hoja in ('grupos')                     then public.puede('tablero.ventas', 'editar')
                                                    or public.puede('tablero.metas', 'editar')
    when p_hoja in ('acciones')                   then public.puede('tablero.mk', 'editar')
                                                    or public.puede('tablero.ventas', 'editar')
    when p_hoja in ('actividad')                  then public.puede('tablero.ventas', 'editar')
                                                    or public.puede('tablero.actividad', 'editar')
    when p_hoja in ('metas', 'direccion')         then public.puede('tablero.metas', 'editar')
    else false
  end;
$$;

revoke execute on function public.puede_llenar_tablero(text) from public, anon;
grant  execute on function public.puede_llenar_tablero(text) to authenticated;

-- La ficha de quien pide, para que una vendedora escriba sólo su actividad.
create or replace function public.mi_ficha_de_vendedor()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select v.id from public.vendedores v where v.usuario_id = (select auth.uid()) limit 1;
$$;

revoke execute on function public.mi_ficha_de_vendedor() from public, anon;
grant  execute on function public.mi_ficha_de_vendedor() to authenticated;

alter table public.tablero_semanal        enable row level security;
alter table public.tablero_metas          enable row level security;
alter table public.tablero_grupos         enable row level security;
alter table public.tablero_acciones       enable row level security;
alter table public.tablero_actividad      enable row level security;
alter table public.tablero_ventas_persona enable row level security;
alter table public.tablero_comentarios    enable row level security;

-- Ver: todas las hojas, quien tenga el Tablero.
drop policy if exists tablero_semanal_ver        on public.tablero_semanal;
drop policy if exists tablero_metas_ver          on public.tablero_metas;
drop policy if exists tablero_grupos_ver         on public.tablero_grupos;
drop policy if exists tablero_acciones_ver       on public.tablero_acciones;
drop policy if exists tablero_actividad_ver      on public.tablero_actividad;
drop policy if exists tablero_ventas_persona_ver on public.tablero_ventas_persona;
drop policy if exists tablero_comentarios_ver    on public.tablero_comentarios;

create policy tablero_semanal_ver        on public.tablero_semanal        for select to authenticated using ((select public.puede('tablero', 'ver')));
create policy tablero_metas_ver          on public.tablero_metas          for select to authenticated using ((select public.puede('tablero', 'ver')));
create policy tablero_grupos_ver         on public.tablero_grupos         for select to authenticated using ((select public.puede('tablero', 'ver')));
create policy tablero_acciones_ver       on public.tablero_acciones       for select to authenticated using ((select public.puede('tablero', 'ver')));
create policy tablero_actividad_ver      on public.tablero_actividad      for select to authenticated using ((select public.puede('tablero', 'ver')));
create policy tablero_ventas_persona_ver on public.tablero_ventas_persona for select to authenticated using ((select public.puede('tablero', 'ver')));
create policy tablero_comentarios_ver    on public.tablero_comentarios    for select to authenticated using ((select public.puede('tablero', 'ver')));

-- Escribir: cada hoja, quien la llena.
drop policy if exists tablero_semanal_llenar        on public.tablero_semanal;
drop policy if exists tablero_metas_llenar          on public.tablero_metas;
drop policy if exists tablero_grupos_llenar         on public.tablero_grupos;
drop policy if exists tablero_acciones_llenar       on public.tablero_acciones;
drop policy if exists tablero_actividad_llenar      on public.tablero_actividad;
drop policy if exists tablero_ventas_persona_llenar on public.tablero_ventas_persona;
drop policy if exists tablero_comentarios_llenar    on public.tablero_comentarios;

-- Marketing sólo los campos mk.*, Ventas sólo los ventas.*.
create policy tablero_semanal_llenar on public.tablero_semanal for all to authenticated
  using      (public.puede_llenar_tablero(split_part(campo, '.', 1)))
  with check (public.puede_llenar_tablero(split_part(campo, '.', 1)));

create policy tablero_metas_llenar on public.tablero_metas for all to authenticated
  using ((select public.puede_llenar_tablero('metas'))) with check ((select public.puede_llenar_tablero('metas')));

create policy tablero_grupos_llenar on public.tablero_grupos for all to authenticated
  using ((select public.puede_llenar_tablero('grupos'))) with check ((select public.puede_llenar_tablero('grupos')));

-- Cada área, sus acciones.
create policy tablero_acciones_llenar on public.tablero_acciones for all to authenticated
  using      (public.puede_llenar_tablero(case responsable when 'MK' then 'mk' else 'ventas' end))
  with check (public.puede_llenar_tablero(case responsable when 'MK' then 'mk' else 'ventas' end));

-- La Gerente, la de todas; cada vendedora, la suya.
create policy tablero_actividad_llenar on public.tablero_actividad for all to authenticated
  using (
    (select public.puede('tablero.ventas', 'editar'))
    or ((select public.puede('tablero.actividad', 'editar')) and vendedor_id = (select public.mi_ficha_de_vendedor()))
  )
  with check (
    (select public.puede('tablero.ventas', 'editar'))
    or ((select public.puede('tablero.actividad', 'editar')) and vendedor_id = (select public.mi_ficha_de_vendedor()))
  );

create policy tablero_ventas_persona_llenar on public.tablero_ventas_persona for all to authenticated
  using ((select public.puede_llenar_tablero('ventas_persona'))) with check ((select public.puede_llenar_tablero('ventas_persona')));

-- El comentario de cada hoja, quien llena esa hoja.
create policy tablero_comentarios_llenar on public.tablero_comentarios for all to authenticated
  using (public.puede_llenar_tablero(hoja)) with check (public.puede_llenar_tablero(hoja));

-- ------------------------------------------------------------------ el módulo

insert into public.modulos (clave, nombre, padre, orden) values
  ('tablero',           'Tablero Comercial',               null,      17),
  ('tablero.mk',        'Llenar lo de Marketing',          'tablero', 171),
  ('tablero.ventas',    'Llenar lo de Ventas',             'tablero', 172),
  ('tablero.actividad', 'Llenar la actividad propia',      'tablero', 173),
  ('tablero.metas',     'Definir metas y cupos',           'tablero', 174)
on conflict (clave) do update
  set nombre = excluded.nombre,
      padre  = excluded.padre,
      orden  = excluded.orden;

-- Cerrado para todos menos Dirección hasta que se decidan los roles. Sólo
-- donde no hay nada guardado: si alguien ya lo abrió, no se le vuelve a cerrar.
insert into public.rol_permisos (rol_id, modulo, ver, crear, editar, eliminar)
select r.id, m.clave, false, false, false, false
  from public.roles r
 cross join (values ('tablero'), ('tablero.mk'), ('tablero.ventas'), ('tablero.actividad'), ('tablero.metas')) as m(clave)
 where not r.es_admin
on conflict (rol_id, modulo) do nothing;

commit;

-- ------------------------------------------------------------- cómo quedó

select
  (select count(*) from information_schema.tables
    where table_schema = 'public' and table_name like 'tablero\_%')            as tablas_del_tablero,
  (select count(*) from public.modulos where clave like 'tablero%')            as casillas_en_roles,
  (select count(*) from public.rol_permisos
    where modulo = 'tablero' and not ver)                                       as roles_que_no_lo_ven;
