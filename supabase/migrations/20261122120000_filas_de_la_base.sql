-- ============================================================================
-- Cada fila del archivo, en su base
-- ============================================================================
--
-- Pedido el 23/10/2026: «Base de egresados-no graduados» traía 285 filas y al
-- desplegarla en Bases se veían 232 nombres. Las filas de una misma persona
-- (mismo teléfono o correo) se unifican en un solo lead, que está bien, pero
-- la base sólo listaba leads y los nombres del archivo se perdían de vista.
--
-- `base_filas` guarda cada fila tal como venía —número de línea, nombre,
-- teléfono, correo— y el lead en el que quedó. Las que no se importaron (sin
-- nombre, omitidas) también quedan, con el motivo. Así la base muestra las
-- 285, y cuáles se juntaron con quién.
--
-- `base_leads` sigue siendo la que usa el filtro «Base» de Clientes: un
-- masivo va a cada contacto una sola vez aunque el archivo lo trajera dos.
--
-- Sólo agrega; no cambia ni borra datos.

create table if not exists public.base_filas (
  id             bigint generated by default as identity primary key,
  importacion_id bigint not null references public.importaciones(id) on delete cascade,
  linea          integer not null,
  nombre         text,
  telefono       text,
  correo         text,
  -- El lead en que quedó la fila. Nulo si no se importó o si el lead se borró.
  oportunidad_id bigint references public.oportunidades(id) on delete set null,
  -- Por qué no se importó, cuando no se importó.
  motivo         text,
  creado_en      timestamptz not null default now(),
  unique (importacion_id, linea)
);

create index if not exists ix_base_filas_oportunidad on public.base_filas (oportunidad_id);

alter table public.base_filas enable row level security;

create policy auth_all_base_filas on public.base_filas
  for all to authenticated using (true) with check (true);
