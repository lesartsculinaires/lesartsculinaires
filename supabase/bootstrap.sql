-- Impedir que se borre o se degrade el último rol administrador.
create or replace function public.protege_admin()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.es_admin then
      raise exception 'No se puede eliminar el rol administrador.';
    end if;
    return old;
  end if;

  if old.es_admin and not new.es_admin
     and not exists (select 1 from public.roles
                     where es_admin and id <> old.id) then
    raise exception 'Debe quedar al menos un rol administrador.';
  end if;
  return new;
end $$;

drop trigger if exists trg_protege_admin on public.roles;
create trigger trg_protege_admin before update or delete on public.roles
  for each row execute function public.protege_admin();


