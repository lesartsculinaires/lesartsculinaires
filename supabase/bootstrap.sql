-- ---------------------------------------------------------------- RLS
--
-- `es_admin()` es SECURITY DEFINER a propósito: las políticas de `usuarios`
-- necesitan leer `usuarios` para decidir, y una política que se consulta a sí
-- misma entra en recursión infinita. Al correr como su creador, la función
-- salta el RLS y corta el ciclo.
create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((
    select r.es_admin
    from public.usuarios u
    join public.roles r on r.id = u.rol_id
    where u.id = (select auth.uid()) and u.activo
  ), false);
$$;

revoke execute on function public.es_admin() from anon;

